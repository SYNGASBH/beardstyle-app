// Lookup by id for O(1) access
export const BEARD_STYLES_MAP = Object.fromEntries(
  BEARD_STYLES.map(s => [s.id, s])
)

// Get styles recommended for a face shape
export function getStylesForShape(faceShape) {
  return BEARD_STYLES
    .filter(s => s.recommendedFor.includes(faceShape))
    .sort((a, b) => a.recommendedFor.length - b.recommendedFor.length)
}
